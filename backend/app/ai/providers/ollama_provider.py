"""
PM Copilot - Ollama Provider
------------------------------
Implements the AIProvider interface for locally running LLMs via Ollama.

Supported Models: llama3.2, qwen2.5, mistral, and any other Ollama model.

VIVA EXPLANATION:
  "Ollama lets us run large language models locally on our machine.
   It exposes a simple HTTP API. I use LangChain's Ollama integration
   which handles the API calls and streaming for us."
"""

from typing import AsyncGenerator

from langchain_ollama import OllamaLLM
from langchain_core.messages import HumanMessage, SystemMessage
from langchain_ollama import ChatOllama

from app.ai.providers.base import AIProvider
from app.config import settings


class OllamaProvider(AIProvider):
    """AI Provider that uses a locally running Ollama instance."""

    def __init__(self):
        self.model_name = settings.ollama_model
        self.base_url = settings.ollama_base_url

        # LangChain's ChatOllama — handles both regular and streaming responses
        self.llm = ChatOllama(
            model=self.model_name,
            base_url=self.base_url,
            temperature=0.7,  # Balanced between creative and factual
        )

    async def generate(self, prompt: str, system_prompt: str = "") -> str:
        """Send a prompt and get a complete response."""
        messages = []

        if system_prompt:
            messages.append(SystemMessage(content=system_prompt))

        messages.append(HumanMessage(content=prompt))

        response = await self.llm.ainvoke(messages)
        return response.content

    async def stream(
        self, prompt: str, system_prompt: str = ""
    ) -> AsyncGenerator[str, None]:
        """Stream the response token by token."""
        messages = []

        if system_prompt:
            messages.append(SystemMessage(content=system_prompt))

        messages.append(HumanMessage(content=prompt))

        # astream() yields chunks as they are generated by the model
        async for chunk in self.llm.astream(messages):
            if chunk.content:
                yield chunk.content

    async def health_check(self) -> bool:
        """Check if Ollama is running and the model is available."""
        try:
            import httpx
            async with httpx.AsyncClient() as client:
                response = await client.get(
                    f"{self.base_url}/api/tags", timeout=5.0
                )
                if response.status_code == 200:
                    models = response.json().get("models", [])
                    model_names = [m["name"] for m in models]
                    return any(self.model_name in name for name in model_names)
        except Exception:
            return False
        return False
